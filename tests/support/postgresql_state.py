"""A test-only PostgreSQL ``SQLDatabase`` for the shared ``SQLStateStore``.

Everything lives in one outer transaction on one psycopg2 connection: a uniquely
named schema holding a PostgreSQL projection of the current state schema. Logical
connections serialize on that connection and use savepoints, and leaving the
context always rolls the outer transaction back, so the server keeps nothing.

Projection of ``CURRENT_DATABASE_SQL`` (everything else runs unchanged):

* ``CHECK (json_valid(x))`` becomes ``CHECK (x::jsonb IS NOT NULL)``.
* ``INTEGER PRIMARY KEY AUTOINCREMENT`` becomes
  ``BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY``.
* Remaining ``INTEGER`` columns become ``BIGINT`` (microsecond timestamps overflow
  PostgreSQL's 32-bit ``INTEGER``; SQLite integers are 64-bit).
* ``key GLOB 'prefix:*'`` becomes ``key LIKE 'prefix:%'``.
* Tables the history creates and later drops are never created, with their
  indexes: SQLite accepts the retired graph's forward foreign keys, PostgreSQL
  does not. The final schema is the same.
"""

from __future__ import annotations

import re
import threading
import uuid
from collections.abc import Iterable, Iterator, Sequence
from contextlib import contextmanager
from types import TracebackType
from typing import Any

import psycopg2  # type: ignore[import-untyped]

from daita.storage.sql import SQLStateStore
from daita.storage.sql_connection import SQLConnection, SQLCursor, StateIntegrityError
from daita.storage.sqlite_schema import CURRENT_DATABASE_SQL

_TRANSLATIONS = (
    (r"CHECK \(json_valid\((\w+)\)\)", r"CHECK (\1::jsonb IS NOT NULL)"),
    (
        r"INTEGER PRIMARY KEY AUTOINCREMENT",
        "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
    ),
    (r"\bINTEGER\b", "BIGINT"),
    (r"key GLOB '([^']*):\*'", r"key LIKE '\1:%'"),
)


def projected_schema_sql() -> str:
    sql = CURRENT_DATABASE_SQL
    for pattern, replacement in _TRANSLATIONS:
        sql = re.sub(pattern, replacement, sql)
    kept: list[str] = []
    for statement in filter(str.strip, sql.split(";\n")):
        dropped = re.match(r"\s*DROP TABLE (\w+)\s*$", statement)
        if dropped is None:
            kept.append(statement)
            continue
        name = dropped.group(1)
        kept = [
            earlier
            for earlier in kept
            if not re.match(rf"\s*CREATE TABLE {name}\b", earlier)
            and not re.search(rf"\bON\s+{name}\s*\(", earlier)
        ]
    return ";\n".join(kept) + ";"


def _translate(query: str) -> str:
    """Turn qmark into ``%s`` and escape ``%``; ``?`` inside literals is kept."""
    out: list[str] = []
    quote = ""
    for char in query:
        if quote:
            quote = "" if char == quote else quote
        elif char in "'\"":
            quote = char
        elif char == "?":
            out.append("%s")
            continue
        out.append("%%" if char == "%" else char)
    return "".join(out)


class _PostgresConnection:
    insertion_order = "ctid"
    distinct_operator = "IS DISTINCT FROM"

    def __init__(self, database: _PostgresDatabase) -> None:
        self._database = database
        database.lock.acquire()
        self._open = True
        self._savepoint: str | None = None

    def _cursor(self) -> Any:
        return self._database.raw.cursor()

    def execute(self, query: str, parameters: Sequence[Any] = ()) -> SQLCursor:
        cursor = self._cursor()
        try:
            if parameters:
                cursor.execute(_translate(query), tuple(parameters))
            else:
                cursor.execute(query)
        except psycopg2.IntegrityError as error:
            raise StateIntegrityError(str(error)) from error
        return cursor

    def executemany(self, query: str, parameters: Iterable[Sequence[Any]]) -> SQLCursor:
        cursor = self._cursor()
        try:
            cursor.executemany(_translate(query), [tuple(row) for row in parameters])
        except psycopg2.IntegrityError as error:
            raise StateIntegrityError(str(error)) from error
        return cursor

    def begin(self, *, write: bool = False) -> None:
        self._savepoint = f"sp_{next(self._database.savepoints)}"
        self._cursor().execute(f"SAVEPOINT {self._savepoint}")

    def commit(self) -> None:
        if self._savepoint is not None:
            self._cursor().execute(f"RELEASE SAVEPOINT {self._savepoint}")
            self._savepoint = None

    def rollback(self) -> None:
        if self._savepoint is not None:
            cursor = self._cursor()
            cursor.execute(f"ROLLBACK TO SAVEPOINT {self._savepoint}")
            cursor.execute(f"RELEASE SAVEPOINT {self._savepoint}")
            self._savepoint = None

    def close(self) -> None:
        if self._open:
            self._open = False
            self._database.lock.release()

    def conflict(self, columns: str) -> str:
        return columns

    def caller_expression(self, column: str) -> str:
        return f"({column}::jsonb -> 'fields' ->> 'caller_principal_id')"

    def table_exists(self, table: str) -> bool:
        cursor = self._cursor()
        cursor.execute(
            "SELECT 1 FROM information_schema.tables "
            "WHERE table_schema = current_schema() AND table_name = %s",
            (table,),
        )
        return cursor.fetchone() is not None

    def __enter__(self) -> SQLConnection:
        return self

    def __exit__(
        self,
        exc_type: type[BaseException] | None,
        exc: BaseException | None,
        traceback: TracebackType | None,
    ) -> None:
        try:
            if exc_type is None:
                self.commit()
            else:
                self.rollback()
        finally:
            self.close()


class _PostgresDatabase:
    def __init__(self, raw: Any, schema: str) -> None:
        self.raw = raw
        self.schema = schema
        self.lock = threading.RLock()
        self.savepoints: Iterator[int] = iter(range(1, 1 << 62))

    def connect(self, *, read_only: bool = False) -> SQLConnection:
        return _PostgresConnection(self)

    def normalize_error(self, error: BaseException) -> BaseException:
        if isinstance(error, psycopg2.IntegrityError):
            return StateIntegrityError(str(error))
        return error


@contextmanager
def postgresql_state(
    password: str,
    *,
    host: str = "127.0.0.1",
    port: int = 55433,
    user: str = "postgres",
) -> Iterator[_PostgresDatabase]:
    """Yield a database whose whole schema is rolled back when the block exits."""
    raw = psycopg2.connect(
        host=host,
        port=port,
        user=user,
        password=password,
        dbname="postgres",
        connect_timeout=10,
    )
    try:
        schema = f"daita_state_{uuid.uuid4().hex}"
        with raw.cursor() as cursor:
            cursor.execute(f'CREATE SCHEMA "{schema}"')
            cursor.execute(f'SET search_path TO "{schema}"')
            cursor.execute(projected_schema_sql())
        yield _PostgresDatabase(raw, schema)
    finally:
        try:
            raw.rollback()
        finally:
            raw.close()


def postgresql_state_store(database: _PostgresDatabase) -> SQLStateStore:
    return SQLStateStore(database)
